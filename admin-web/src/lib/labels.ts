// Mapa que asocia cada hábito con su diccionario completo y aislado
const HABIT_DICTIONARIES: Record<string, Record<string, string>> = {
  'Árbol': LABELS_ARBOL,
  'Palmera': LABELS_PALMERA,
  'Arbusto': LABELS_ARBUSTO,
  'Liana': LABELS_LIANA,
  'Hierba': LABELS_HIERBA,
};

export const formatLabel = (key: string, habito?: string) => {
  const normalizedKey = key.toLowerCase();
  
  // Buscar estrictamente en el diccionario del hábito correspondiente
  if (habito && HABIT_DICTIONARIES[habito]) {
    if (HABIT_DICTIONARIES[habito][normalizedKey]) {
      return HABIT_DICTIONARIES[habito][normalizedKey];
    }
    if (HABIT_DICTIONARIES[habito][key]) {
      return HABIT_DICTIONARIES[habito][key];
    }
  }

  // Fallback: si no encuentra la traducción, formatea la variable para que se vea legible
  return key.replace(/_/g, ' ').replace(/\b\w/g, l => l.toUpperCase());
};
